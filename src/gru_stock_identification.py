# General libraries
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import os

# Machine Learning and Preprocessing
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, StandardScaler, OneHotEncoder
from sklearn.model_selection import KFold

# TensorFlow and Keras
from tensorflow.keras import Input, Model
from tensorflow.keras.layers import (Embedding, GRU, Concatenate, Dense, Bidirectional, Flatten,
                                     Activation)
from tensorflow.keras.models import Model
from tensorflow.keras.optimizers import Adam
from tensorflow.keras.utils import to_categorical, plot_model
from tensorflow.keras.callbacks import EarlyStopping, ModelCheckpoint, ReduceLROnPlateau
from tensorflow.keras.preprocessing.sequence import pad_sequences


# Challenge files (challengedata.ens.fr, challenge 146), placed in data/
path_X_train = 'data/X_train_N1UvY30.csv'
path_Y_train = 'data/y_train_or6m3Ta.csv'
path_X_test = 'data/X_test_m4HAPAP.csv'
path_Y_test = 'data/y_random_cfm.csv'

# Loading the data
X_train = pd.read_csv(path_X_train)
Y_train = pd.read_csv(path_Y_train)
X_test = pd.read_csv(path_X_test)
Y_test = pd.read_csv(path_Y_test)


print(X_test.columns)
print(X_train.columns)
print("Number of columns in X_test:", len(X_test.columns))
print("Number of columns in X_train:", len(X_test.columns))
print(X_train.head())
print("Number of rows:", len(X_train))


#  mapping and encoding
X_train['side'] = X_train['side'].map({'A': 0, 'B': 1}).astype(int)
X_test['side'] = X_test['side'].map({'A': 0, 'B': 1}).astype(int)

action_mapping = {'A': 1, 'D': 0, 'U': 2}
X_train['action'] = X_train['action'].map(action_mapping)
X_test['action'] = X_test['action'].map(action_mapping)


X_train['trade'] = X_train['trade'].fillna(False).astype(int)
X_test['trade'] = X_test['trade'].fillna(False).astype(int)

numeric_features = ['price', 'bid', 'ask', 'bid_size', 'ask_size', 'flux']

# Convert to numeric
for feature in numeric_features:
    X_train[feature] = pd.to_numeric(X_train[feature], errors='coerce').fillna(X_train[feature].median())
    X_test[feature] = pd.to_numeric(X_test[feature], errors='coerce').fillna(X_test[feature].median())
    X_train[feature] = np.log1p(X_train[feature].clip(lower=1))
    X_test[feature] = np.log1p(X_test[feature].clip(lower=1))


X_train.replace([np.inf, -np.inf], np.nan, inplace=True)
X_test.replace([np.inf, -np.inf], np.nan, inplace=True)

# Prepare sequences
sequences = []
labels = []

for obs_id, group in X_train.groupby('obs_id'):
    group = group.sort_values(by='order_id')

    sequence = group[['venue', 'action', 'trade', 'side'] + numeric_features].values
    sequences.append(sequence)
    label = Y_train[Y_train['obs_id'] == obs_id]['eqt_code_cat'].iloc[0]
    labels.append(label)


sequences_padded = pad_sequences(sequences, maxlen=100, dtype='float32', padding='post', truncating='post')
labels_encoded = to_categorical(np.array(labels), num_classes=24)


import matplotlib.pyplot as plt


X_train[numeric_features].hist(bins=50, figsize=(20,15))
plt.show()  # histograms



print("X_train Descriptive Statistics:")
print(X_train[numeric_features].describe())


print("\nY_train Descriptive Statistics:")
print(Y_train.describe())


# Define maximum values
max_venue = int(np.max([seq[:, 0] for seq in sequences_padded])) + 1

max_action = X_train['action'].max() + 1
max_trade = 2

# Prepare inputs
X_train_seq, X_val_seq, Y_train_enc, Y_val_enc = train_test_split(sequences_padded, labels_encoded, test_size=0.2, random_state=42)

# Splitting into separate inputs
X_train_venue = np.array([seq[:, 0] for seq in X_train_seq]).astype('int32')
X_train_action = np.array([seq[:, 1] for seq in X_train_seq]).astype('int32')
X_train_trade = np.array([seq[:, 2] for seq in X_train_seq]).astype('int32')
X_train_numerical = np.array([seq[:, 4:] for seq in X_train_seq])

X_val_venue = np.array([seq[:, 0] for seq in X_val_seq]).astype('int32')
X_val_action = np.array([seq[:, 1] for seq in X_val_seq]).astype('int32')
X_val_trade = np.array([seq[:, 2] for seq in X_val_seq]).astype('int32')
X_val_numerical = np.array([seq[:, 4:] for seq in X_val_seq])


# Input layers
input_venue = Input(shape=(100,), name='venue_input')
input_action = Input(shape=(100,), name='action_input')
input_trade = Input(shape=(100,), name='trade_input')
numerical_input = Input(shape=(100, 6), name='numerical_input')
# Embeddings
embedding_venue = Embedding(input_dim=max_venue, output_dim=8)(input_venue)
embedding_action = Embedding(input_dim=max_action, output_dim=8)(input_action)
embedding_trade = Embedding(input_dim=max_trade, output_dim=8)(input_trade)


# Concatenate
all_features = Concatenate()([embedding_venue, embedding_action, embedding_trade, numerical_input])

# GRU layers
gru_layer = Bidirectional(GRU(64, return_sequences=True))(all_features)
gru_layer = Bidirectional(GRU(64, return_sequences=False))(gru_layer)

# Dense layers
dense_layer = Dense(64, activation='selu')(gru_layer)

# Final output layer
output_layer = Dense(24, activation='softmax')(dense_layer)

# model
model = Model(inputs=[input_venue, input_action, input_trade, numerical_input], outputs=output_layer)
model.compile(optimizer=Adam(learning_rate=3e-3), loss='categorical_crossentropy', metrics=['accuracy'])




model.summary()


# callbacks
early_stopping = EarlyStopping(monitor='val_loss', patience=5, verbose=1, restore_best_weights=True)
model_checkpoint = ModelCheckpoint('best_model.keras', monitor='val_loss', save_best_only=True, verbose=1)
reduce_lr = ReduceLROnPlateau(monitor='val_loss', factor=0.1, patience=3, verbose=1)

#epochs and callbacks
history = model.fit(
    [X_train_venue, X_train_action, X_train_trade, X_train_numerical],
    Y_train_enc,
    epochs=100,
    validation_split=0.2,
    batch_size=1000,
    callbacks=[early_stopping, model_checkpoint, reduce_lr]
)

training_loss = history.history['loss']
validation_loss = history.history['val_loss']
training_accuracy = history.history['accuracy']
validation_accuracy = history.history['val_accuracy']
model.save('final_model.keras')



plt.figure(figsize=(12, 8))
plt.plot(training_loss, label='Training Loss')
plt.plot(validation_loss, label='Validation Loss')
plt.legend()
plt.title('Training and Validation Loss Over Epochs')
plt.xlabel('Epochs')
plt.ylabel('Loss')
plt.show()


plt.figure(figsize=(12, 8))
plt.plot(training_accuracy, label='Training Accuracy')
plt.plot(validation_accuracy, label='Validation Accuracy')
plt.legend()
plt.title('Training and Validation Accuracy Over Epochs')
plt.xlabel('Epochs')
plt.ylabel('Accuracy')
plt.show()